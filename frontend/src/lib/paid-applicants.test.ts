import { test } from "node:test";
import assert from "node:assert/strict";
import { NOT_AVAILABLE, PAID_HEAD, aggregateCell, paidFileName, paidHeading, paidLine, paidQuery, readPaidFilters, withPaidChange, EMPTY_PAID, type PaidRow } from "./paid-applicants.ts";

const ROW: PaidRow = {
  jamb_reg_no: "202660110469AJ", full_name: "ABALIKE, Emmanuel", programme: "B.Sc. Computer Science", sex: "M", entry_mode: "UTME",
  utme_aggregate: 231, phone: "08031234567", email: "abalike@example.com", payment_status: "VERIFIED", missing: [],
};

test("the address is read back only where each value has its shape", () => {
  const f = readPaidFilters({ session: "2026/2027", status: "PENDING", fac: "SC", dept: "MTC; DROP", sex: "X", entry: "DIRECT_ENTRY",
    from: "2026-09-01", to: "not-a-date", jamb: "2026'--", q: "  okoh  " });
  assert.equal(f.session, "2026/2027");
  assert.equal(f.status, "PENDING");
  assert.equal(f.fac, "SC");
  assert.equal(f.dept, "");
  assert.equal(f.sex, "");
  assert.equal(f.entry, "DIRECT_ENTRY");
  assert.equal(f.from, "2026-09-01");
  assert.equal(f.to, "");
  assert.equal(f.jamb, "");
  assert.equal(f.q, "okoh");
  assert.equal(readPaidFilters({ status: "PAID" }).status, "");
  assert.equal(readPaidFilters({ session: "2026-2027" }).session, "");
});

test("the API query leaves the session to the path; the address keeps it", () => {
  const f = { ...EMPTY_PAID, session: "2026/2027", fac: "SC", sex: "F" };
  assert.equal(paidQuery(f, { page: 2 }, false), "fac=SC&sex=F&page=2");
  assert.equal(paidQuery(f), "session=2026%2F2027&fac=SC&sex=F");
});

test("a faculty change clears the department and programme; a department change the programme", () => {
  const f = { ...EMPTY_PAID, session: "2026/2027", fac: "SC", dept: "MTC", prog: "C00023" };
  assert.deepEqual([withPaidChange(f, "fac", "AR").dept, withPaidChange(f, "fac", "AR").prog], ["", ""]);
  assert.equal(withPaidChange(f, "dept", "PHY").prog, "");
  assert.equal(withPaidChange(f, "sex", "F").prog, "C00023");
});

test("the eight columns in the asked order; S/N is the engines' own", () => {
  assert.deepEqual(PAID_HEAD, ["JAMB Registration Number", "Candidate's Full Name", "Course/Programme Applied For", "Gender", "UTME Aggregate Score", "Phone Number", "Email Address"]);
  assert.deepEqual(paidLine(ROW), ["202660110469AJ", "ABALIKE, Emmanuel", "B.Sc. Computer Science", "Male", 231, "08031234567", "abalike@example.com"]);
});

test("what is missing is said, never invented: the aggregate is JAMB's or NOT AVAILABLE", () => {
  const bare: PaidRow = { ...ROW, jamb_reg_no: null, programme: null, sex: null, utme_aggregate: null, phone: null, email: null, missing: ["JAMB_NUMBER"] };
  assert.deepEqual(paidLine(bare), [NOT_AVAILABLE, "ABALIKE, Emmanuel", NOT_AVAILABLE, NOT_AVAILABLE, NOT_AVAILABLE, NOT_AVAILABLE, NOT_AVAILABLE]);
  assert.equal(aggregateCell({ utme_aggregate: null, entry_mode: "DIRECT_ENTRY" }), "NOT AVAILABLE (DIRECT ENTRY)");
  assert.equal(aggregateCell({ utme_aggregate: 0, entry_mode: "UTME" }), 0);
  // a phone number keeps its leading zero: it is text, not a number
  assert.equal(typeof paidLine(ROW)[5], "string");
});

test("the heading names the session, the status, the filters, when, by whom and how many", () => {
  const f = { ...EMPTY_PAID, session: "2026/2027", fac: "SC", sex: "F", from: "2026-09-01" };
  const h = paidHeading(f, { faculty: "Faculty of Science" }, 1234, "OKOH, Ada", "15 Oct 2026, 10:05");
  assert.equal(h.title, "PAID POST-UTME APPLICANTS");
  const meta = Object.fromEntries(h.meta);
  assert.equal(meta["Admission session"], "2026/2027");
  assert.equal(meta["Payment status"], "Paid (verified)");
  assert.equal(meta["Filters"], "Faculty: Faculty of Science · Gender: Female · Paid from 2026-09-01");
  assert.equal(meta["Generated by"], "OKOH, Ada");
  assert.equal(meta["Total applicants"], "1,234");
  assert.equal(paidHeading({ ...f, status: "PENDING" }, {}, 0, null, "").title, "POST-UTME APPLICANTS — PENDING — NOT CONFIRMED");
  assert.equal(Object.fromEntries(paidHeading({ ...EMPTY_PAID, session: "2026/2027" }, {}, 0, null, "").meta)["Filters"], "None — every applicant in your scope");
});

test("the file name carries the session and the narrowest unit", () => {
  assert.equal(paidFileName({ ...EMPTY_PAID, session: "2026/2027" }, "xlsx"), "paid-post-utme-applicants-2026-2027.xlsx");
  assert.equal(paidFileName({ ...EMPTY_PAID, session: "2026/2027", fac: "SC", prog: "C00023" }, "pdf"), "paid-post-utme-applicants-2026-2027-c00023.pdf");
  assert.equal(paidFileName({ ...EMPTY_PAID, session: "2026/2027", status: "NOT_STARTED" }, "xlsx"), "paid-post-utme-applicants-2026-2027-not-started.xlsx");
});
