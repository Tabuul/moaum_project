-- ═══════════════════════════════════════════════════════════════════════════════════════════════
-- V314 — GST & EPS: the fee the Bursar states, the entitlement a verified payment grants, the gate on
--        registration, and the two offices that run the courses
--
--   General Studies (GST) and Entrepreneurship Studies (EPS) are two academic offices over the courses the
--   catalogue already carries as kind 'GST' (V013, V116, V172: a GST/EPS course is one of kind GST, offered to
--   a programme on basis GST, registered as an entry of type GST). Nothing of that changes. What is added:
--
--     1  two offices on the register, 'gst' and 'eps', with the courses split between them by
--        catalogue.course.general_office — GST or EPS — derived from the code and title once and kept by a
--        trigger, editable by the office that owns the course.
--     2  the GST fee: a separate obligation from school fees, stated by the Bursar per session in
--        finance.gst_fee, scoped where needed to a level, an entry mode, a faculty or a programme; a new
--        statement supersedes the old and never touches a payment already made. ONE payment covers GST and
--        EPS (finance.gst_setting.covers_eps); there is no EPS fee.
--     3  the entitlement: finance.gst_entitlement(student, session) reads the CONFIRMED references of purpose
--        'GST fee <session>' on finance.payment_reference — the same ledger, the same confirmation as every
--        other payment — net of any approved or paid refund, and says whether the student is entitled. The
--        reference is generated by finance.new_gst_reference and paid on the gateway like any other.
--     4  the gate: registration.gst_gate refuses a GST or EPS course on a registration while the GST fee is
--        stated and unpaid (finance.gst_setting.required_for_gst_eps, on by default); it may also be set to
--        hold the whole registration (required_for_all, off by default). The refusal is raised by
--        registration.student_choose, student_add and student_submit themselves, so no path round the API
--        registers an unpaid student; the message names the fee and the way to pay it.
--     5  what the offices read: finance.gst_population (one row per undergraduate with their requirement,
--        fee, payment, entitlement and GST/EPS registrations for a session) and finance.gst_course_stats
--        (one row per GST/EPS offering with its registrations, its score sheet and its stage) — set-based,
--        for the dashboards, the lists and the exports.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

