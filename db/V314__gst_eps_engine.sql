CREATE OR REPLACE FUNCTION catalogue.general_office_of(p_code text, p_title text, p_kind text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN coalesce(p_kind, '') <> 'GST' THEN NULL
                WHEN upper(coalesce(p_code, '')) ~ '^(EPS|ENT)[ -]?[0-9]' OR coalesce(p_title, '') ~* '(entrepreneur|enterprise|venture)' THEN 'EPS'
                ELSE 'GST' END
$$;
COMMENT ON FUNCTION catalogue.general_office_of(text, text, text) IS
  'The office a general course belongs to by its code and title (V314): EPS for an EPS/ENT code or an entrepreneurship title, GST for the rest of kind GST, NULL otherwise.';

UPDATE catalogue.course SET general_office = catalogue.general_office_of(code, title, kind) WHERE kind = 'GST' AND general_office IS NULL;

CREATE OR REPLACE FUNCTION catalogue.course_general_office()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind <> 'GST' THEN
        NEW.general_office := NULL;
    ELSIF NEW.general_office IS NULL THEN
        NEW.general_office := catalogue.general_office_of(NEW.code, NEW.title, NEW.kind);
    END IF;
    RETURN NEW;
END $$;
