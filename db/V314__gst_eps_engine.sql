-- ── 3 · the GST fee, stated by the Bursar per session; a new statement supersedes, never edits ─
CREATE TABLE finance.gst_fee (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    session        text NOT NULL REFERENCES policy.academic_session(name),
    amount         numeric(12,2) NOT NULL CHECK (amount >= 0),
    level          int NULL CHECK (level IS NULL OR level IN (100, 200, 300, 400, 500, 600)),
    entry_mode     text NULL CHECK (entry_mode IS NULL OR entry_mode IN ('UTME', 'DIRECT_ENTRY', 'TRANSFER', 'JUPEB', 'SANDWICH')),
    faculty_code   text NULL REFERENCES ref.faculty(code),
    programme_code text NULL REFERENCES ref.programme(code),
    effective_from date NOT NULL DEFAULT current_date,
    note           text NULL,
    stated_by      uuid NULL,
    stated_office  text NULL,
    stated_at      timestamptz NOT NULL DEFAULT now(),
    superseded_at  timestamptz NULL
);
COMMENT ON TABLE finance.gst_fee IS
  'The GST fee per session (V314), stated by the Bursar: a general rule, or one scoped to a level, an entry mode, a faculty or a programme; the most specific live rule prices a student. A new statement supersedes the old; a payment already confirmed keeps its own amount.';
CREATE INDEX ix_gst_fee_live ON finance.gst_fee (session) WHERE superseded_at IS NULL;
